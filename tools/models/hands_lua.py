# out/ViewHands.json (written by hands.py) -> src/shared/HandParts.lua: the hand's joints and each piece's middle.
import json, os
S = os.path.dirname(os.path.abspath(__file__))
spec = json.load(open(os.path.join(S, "out", "ViewHands.json")))
def v3(v):
    return "Vector3.new(%s, %s, %s)" % tuple(("%.4f" % x).rstrip("0").rstrip(".") if x else "0" for x in v)
out = ["-- Generated by tools/models/hands_lua.py from tools/models/hands.py: do not edit by hand.",
       "-- The first-person hand (Assets.FrontBodies.Hands) in its own frame: the wrist at the origin, the fingers toward -Y,",
       "-- the thumb on the -Z side, the palm facing -X on a right hand (+X on a left). Root = the knuckle; Lengths and",
       "-- Radius = the three joints from the knuckle out; Centres = each piece's middle from its own joint (the palm's",
       "-- from the wrist); Sizes = each bare piece's box.",
       "local HandParts = {}", "", "HandParts.Order = { \"Thumb\", \"Index\", \"Middle\", \"Ring\", \"Pinky\" }", "HandParts.Digits = {"]
for name in ["Thumb", "Index", "Middle", "Ring", "Pinky"]:
    d = spec["Digits"][name]
    out.append("\t%s = { Pieces = { %s }, Root = %s, Lengths = { %s }, Radius = { %s } }," % (name, ", ".join('"%s"' % p for p in d["pieces"]),
        v3(d["root"]), ", ".join("%g" % x for x in d["lengths"]), ", ".join("%g" % x for x in d["radius"])))
out += ["}", "HandParts.Thenar = %s" % v3(spec["Thenar"]), "HandParts.PalmHalf = %g" % spec["PalmHalf"], "HandParts.Centres = {"]
for k, v in spec["Centres"].items():
    out.append("\t%s = %s," % (k, v3(v)))
out += ["}", "HandParts.Sizes = {"]
for k, v in spec["Sizes"].items():
    out.append("\t%s = %s," % (k, v3(v)))
out += ["}", "", "return HandParts", ""]
open(os.path.join(S, "..", "..", "src", "shared", "HandParts.lua"), "w").write("\n".join(out))
print("wrote src/shared/HandParts.lua")
